/**
 * 根据语言模式翻译单个文本
 * @param {string} rawText 原始文本
 * @param {'zh-CN' | 'bilingual' | 'en-US'} mode 语言模式
 * @param {Record<string, string>} customDict 用户自定义词典
 * @returns {string | null} 若命中翻译则返回目标文本，否则返回 null
 */
export function translateText(rawText, mode = 'zh-CN', customDict = {}) {
  if (!rawText || typeof rawText !== 'string') return null;
  if (mode === 'en-US') return rawText;

  const trimmed = rawText.trim();
  if (!trimmed || trimmed.length > 260) return null;

  // 1. 优先匹配用户自定义词典与内置精确词典
  let zh = customDict[trimmed] || EXACT_DICT[trimmed];

  // 2. 尝试动态正则匹配
  if (!zh) {
    for (const rule of PATTERN_RULES) {
      if (rule.pattern.test(trimmed)) {
        zh = trimmed.replace(rule.pattern, rule.replace);
        break;
      }
    }
  }

  if (!zh) return null;

  // 保留首尾空白符
  const leadingSpace = rawText.match(/^\s*/)?.[0] || '';
  const trailingSpace = rawText.match(/\s*$/)?.[0] || '';

  if (mode === 'bilingual') {
    // 对于短标签（<= 28 字符）展示中英双语，长描述直接展示中文以保证排版美观
    if (trimmed.length <= 28 && zh !== trimmed) {
      return `${leadingSpace}${zh} · ${trimmed}${trailingSpace}`;
    }
  }

  return `${leadingSpace}${zh}${trailingSpace}`;
}
